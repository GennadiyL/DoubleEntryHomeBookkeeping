using Microsoft.Extensions.DependencyInjection;
using NUnit.Framework;
using NSubstitute;
using Shared.Contracts;
using Shared.Contracts.Config;
using Shared.Impl;

namespace UnitTests.Shared;

/// <summary>
/// Verifies scope-owned temporary directory allocation and cleanup.
/// Resolves the production service through the shared DI module.
/// Repeated and concurrent requests must share one directory per scope.
/// Independent scopes must never delete each other's temporary files.
/// Missing directories are recreated at the cached path.
/// Both disposal modes remove nested temporary content.
/// An unused service must perform no directory operations.
/// Only directories generated by the tested service are removed.
/// </summary>
[TestFixture(Category = "Local")]
public sealed class ConfigurationServiceTests
{
	[TestCase(false)]
	[TestCase(true)]
	public async Task ScopeDisposalRemovesOwnedContents(bool asynchronous)
	{
		using ServiceProvider provider = CreateProvider();
		AsyncServiceScope scope = provider.CreateAsyncScope();
		IConfigurationService service = scope.ServiceProvider.GetRequiredService<IConfigurationService>();
		string path = service.GetTempDirectory();
		try
		{
			Assert.That(scope.ServiceProvider.GetRequiredService<ISharedContext>().ConfigurationService, Is.SameAs(service));
			Directory.CreateDirectory(Path.Combine(path, "nested"));
			await File.WriteAllTextAsync(Path.Combine(path, "nested", "content.txt"), "temporary");
		}
		finally
		{
			if (asynchronous)
			{
				await scope.DisposeAsync();
			}
			else
			{
				scope.Dispose();
			}
		}
		Assert.That(Directory.Exists(path), Is.False);
		Assert.Throws<ObjectDisposedException>(() => service.GetTempDirectory());
		await ((IAsyncDisposable)service).DisposeAsync();
	}

	[Test]
	public async Task ConcurrentRequestsCacheOnePathAndRecreateMissingDirectory()
	{
		using ServiceProvider provider = CreateProvider();
		using IServiceScope scope = provider.CreateScope();
		IConfigurationService service = scope.ServiceProvider.GetRequiredService<IConfigurationService>();
		string[] paths = await Task.WhenAll(Enumerable.Range(0, 16).Select(_ => Task.Run(service.GetTempDirectory)));
		Assert.That(paths.Distinct().Count(), Is.EqualTo(1));
		Directory.Delete(paths[0]);
		Assert.That(service.GetTempDirectory(), Is.EqualTo(paths[0]));
		Assert.That(Directory.Exists(paths[0]), Is.True);
	}

	[Test]
	public void IndependentScopesOwnIndependentDirectories()
	{
		using ServiceProvider provider = CreateProvider();
		using IServiceScope second = provider.CreateScope();
		string secondPath = second.ServiceProvider.GetRequiredService<IConfigurationService>().GetTempDirectory();
		string firstPath;
		using (IServiceScope first = provider.CreateScope())
		{
			firstPath = first.ServiceProvider.GetRequiredService<IConfigurationService>().GetTempDirectory();
			Assert.That(firstPath, Is.Not.EqualTo(secondPath));
		}
		Assert.That(Directory.Exists(firstPath), Is.False);
		Assert.That(Directory.Exists(secondPath), Is.True);
	}

	[Test]
	public void UnusedServiceDoesNotAllocateOrDeleteDirectory()
	{
		IDirectoryService directories = Substitute.For<IDirectoryService>();
		ServiceCollection services = new();
		services.AddSharedModule();
		services.AddSingleton(directories);
		using ServiceProvider provider = services.BuildServiceProvider();
		using (IServiceScope scope = provider.CreateScope())
		{
			scope.ServiceProvider.GetRequiredService<IConfigurationService>();
		}
		Assert.That(directories.ReceivedCalls(), Is.Empty);
	}

	private static ServiceProvider CreateProvider()
	{
		ServiceCollection services = new();
		services.AddSharedModule();
		return services.BuildServiceProvider(new ServiceProviderOptions { ValidateScopes = true });
	}
}
